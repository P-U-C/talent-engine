@dataclass
class RepoActivity:
    name: str  # "owner/repo"
    owner: str
    is_fork: bool
    pushed_at: str | None
    created_at: str | None
    description: str = ""
    language: str | None = None
    topics: list[str] = field(default_factory=list)
    stars: int = 0
    has_releases: bool = False
    has_pages: bool = False
    has_description: bool = False
    homepage: str = ""
    license: str | None = None
    commits_in_window: int = 0
    commit_weeks: list[str] = field(default_factory=list)

    @property
    def url(self) -> str:
        return f"https://github.com/{self.name}"


@dataclass
class PullRequestActivity:
    repo: str  # "owner/repo"
    number: int
    title: str
    merged_at: str | None
    created_at: str | None
    is_own_repo: bool = False

    @property
    def url(self) -> str:
        return f"https://github.com/{self.repo}/pull/{self.number}"


@dataclass
class ReviewActivity:
    repo: str
    number: int
    submitted_at: str | None
    is_own_repo: bool = False

    @property
    def url(self) -> str:
        return f"https://github.com/{self.repo}/pull/{self.number}"


@dataclass
class Application:
    """Self-declared fields.

    Invariant 2: nothing about a person's background or circumstances may be
    inferred.  It enters here, from the person, or through a verified referrer,
    or not at all.  There is deliberately no field for anything derived from a
    name, location, photo, or avatar.
    """

    context_statement: str = ""
    context_factors: list[str] = field(default_factory=list)
    referrer_name: str = ""
    declared_repo: str = ""
    build_plan: str = ""  # collected, surfaced to reviewers, unscored by default
    # Did the applicant affirmatively accept the programme terms, and which
    # version. Displaying terms on a page is not agreement; an affirmative act
    # is, and it has to say what was agreed to or it means nothing later.
    accepted_terms: bool = False
    accepted_terms_version: str = ""
    extra: dict[str, Any] = field(default_factory=dict)


@dataclass
class ProfileSnapshot:
    """Everything the scorer sees. Serialisable, hashable, replayable."""

    handle: str
    account_created_at: str | None
    collected_at: str
    window_start: str
    window_end: str
    repos: list[RepoActivity] = field(default_factory=list)
    merged_prs: list[PullRequestActivity] = field(default_factory=list)
    reviews: list[ReviewActivity] = field(default_factory=list)
    active_weeks: list[str] = field(default_factory=list)
    application: Application = field(default_factory=Application)
    collection_notes: list[str] = field(default_factory=list)
    partial: bool = False

    @property
    def profile_url(self) -> str:
        return f"https://github.com/{self.handle}"

    @property
    def account_age_days(self) -> int | None:
        if not self.account_created_at:
            return None
        created = _parse_iso(self.account_created_at)
        end = _parse_iso(self.window_end)
        if created is None or end is None:
            return None
        return (end - created).days

    @property
    def original_repos(self) -> list[RepoActivity]:
        """Non-fork repos with a push inside the window.

        The "original" qualifier is doing real work: forked shells are the
        cheapest thing to manufacture, so they earn nothing on the agency
        dimension.
        """
        return [r for r in self.repos if not r.is_fork and r.commits_in_window > 0]

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    def digest(self) -> str:
        """Stable content hash -- the anchor for reproducing a historical score."""
        payload = json.dumps(self.to_dict(), sort_keys=True, separators=(",", ":"))
        return "sha256:" + hashlib.sha256(payload.encode()).hexdigest()[:32]


# --------------------------------------------------------------------------
# helpers
# --------------------------------------------------------------------------


def _parse_iso(value: str | None) -> datetime | None:
    if not value:
        return None
    text = value.replace("Z", "+00:00")
    try:
        dt = datetime.fromisoformat(text)
    except ValueError:
        return None
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt


def iso_week(value: str | None) -> str | None:
    """ISO year-week key, e.g. '2026-W23'. The unit of the cadence signal."""
    dt = _parse_iso(value)
    if dt is None:
        return None
    year, week, _ = dt.isocalendar()
    return f"{year}-W{week:02d}"


def utc_now_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def dedupe_weeks(weeks: Iterable[str | None]) -> list[str]:
    """Distinct, sorted week keys.

    v1 double-counted weeks that appeared in more than one activity source
    (a push and a PR in the same week read as two).  Cadence is 'did this
    person show up that week', so the sources are unioned, not summed.
    """
    return sorted({w for w in weeks if w})

"""Core data model.

Two hard structural rules live here, because invariants that are only written
down in a README get violated eventually:

1.  Every point awarded carries `Evidence` with a source URL.  `DimensionScore`
    refuses to hold points without it, so an unevidenced score cannot be
    constructed at all.
2.  `Flag` has no points field.  Flags route to human review; they can never
    add score.  Some flags carry a `discount` that *reduces* a dimension's
    contribution (see scoring.flags), but nothing here can increase one.

The scoring pipeline is split into collection (network) and scoring (pure).
`ProfileSnapshot` is the seam: it is everything the scorer is allowed to see.
Because it is a plain serialisable record, any historical score can be
regenerated byte-for-byte from a stored snapshot plus a code version and a
weight set -- which is what the audit log requires.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field, asdict
from datetime import datetime, timezone
from typing import Any, Iterable

SCHEMA_VERSION = "1.0.0"


# --------------------------------------------------------------------------
# Evidence
# --------------------------------------------------------------------------


@dataclass(frozen=True)
class Evidence:
    """A single verifiable claim backing part of a score.

    `url` must be a public, human-openable link.  A candidate reading their own
    dossier has to be able to click every line of it.
    """

    claim: str
    url: str
    detail: str = ""

    def __post_init__(self) -> None:
        if not self.claim:
            raise ValueError("evidence requires a claim")
        if not self.url or not self.url.startswith(("http://", "https://")):
            raise ValueError(f"evidence requires a public URL, got {self.url!r}")

    def to_dict(self) -> dict[str, str]:
        return {"claim": self.claim, "url": self.url, "detail": self.detail}


# --------------------------------------------------------------------------
# Scores
# --------------------------------------------------------------------------


@dataclass
class DimensionScore:
    """Points earned on one rubric dimension, with the arithmetic exposed.

    `components` records the named sub-parts that produced `raw`, so a dossier
    can show "original repos 8.5 + commit volume 6.0 + completeness 4.0"
    rather than an unexplained 18.5.
    """

    key: str
    points: float
    max_points: float
    components: dict[str, float] = field(default_factory=dict)
    evidence: list[Evidence] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    def __post_init__(self) -> None:
        if self.points < 0:
            raise ValueError(f"{self.key}: negative points ({self.points})")
        if self.points > self.max_points + 1e-9:
            raise ValueError(
                f"{self.key}: {self.points} exceeds dimension max {self.max_points}"
            )
        # Invariant 3: transparency. Points without a citation are not auditable,
        # so we refuse to build them.
        if self.points > 0 and not self.evidence:
            raise ValueError(
                f"{self.key}: {self.points} points awarded with no evidence -- "
                "every claim must link to its source"
            )
        self.points = round(float(self.points), 4)

    def to_dict(self) -> dict[str, Any]:
        return {
            "key": self.key,
            "points": round(self.points, 2),
            "max_points": self.max_points,
            "components": {k: round(v, 3) for k, v in self.components.items()},
            "evidence": [e.to_dict() for e in self.evidence],
            "notes": list(self.notes),
        }


@dataclass(frozen=True)
class Flag:
    """An authenticity or review signal.

    Deliberately has no points field.  `discount` is a multiplier in [0, 1]
    applied to a specific dimension component by the scorer; it can only ever
    shrink a score.  Invariant 4: flags never add score.
    """

    key: str
    severity: str  # "review" | "warn" | "critical"
    message: str
    evidence: tuple[Evidence, ...] = ()
    discount: float | None = None
    discounts_component: str | None = None

    def __post_init__(self) -> None:
        if self.severity not in ("review", "warn", "critical"):
            raise ValueError(f"unknown severity {self.severity!r}")
        if self.discount is not None and not (0.0 <= self.discount <= 1.0):
            raise ValueError(
                f"{self.key}: discount {self.discount} outside [0,1] -- "
                "flags may only reduce score"
            )

    def to_dict(self) -> dict[str, Any]:
        out: dict[str, Any] = {
            "key": self.key,
            "severity": self.severity,
            "message": self.message,
            "evidence": [e.to_dict() for e in self.evidence],
        }
        if self.discount is not None:
            out["discount"] = self.discount
            out["discounts_component"] = self.discounts_component
        return out


@dataclass
class CandidateScore:
    handle: str
    total: float
    dimensions: list[DimensionScore]
    flags: list[Flag]
    program: str
    window_start: str
    window_end: str
    snapshot_digest: str
    code_version: str
    scored_at: str
    weights_digest: str = ""

    @property
    def automated_total(self) -> float:
        return round(
            sum(d.points for d in self.dimensions if d.key in AUTOMATED_DIMENSIONS), 2
        )

    @property
    def application_total(self) -> float:
        return round(
            sum(d.points for d in self.dimensions if d.key in APPLICATION_DIMENSIONS), 2
        )

    def dimension(self, key: str) -> DimensionScore | None:
        for d in self.dimensions:
            if d.key == key:
                return d
        return None

    def to_dict(self) -> dict[str, Any]:
        return {
            "handle": self.handle,
            "total": round(self.total, 2),
            "automated_total": self.automated_total,
            "application_total": self.application_total,
            "program": self.program,
            "window": {"start": self.window_start, "end": self.window_end},
            "dimensions": [d.to_dict() for d in self.dimensions],
            "flags": [f.to_dict() for f in self.flags],
            "reproducibility": {
                "snapshot_digest": self.snapshot_digest,
                "weights_digest": self.weights_digest,
                "code_version": self.code_version,
                "schema_version": SCHEMA_VERSION,
                "scored_at": self.scored_at,
            },
        }


AUTOMATED_DIMENSIONS = (
    "shipping_agency",
    "consistency",
    "external_validation",
    "collaboration",
    "ecosystem_footprint",
    "frontier_signal",
)

APPLICATION_DIMENSIONS = (
    "context_statement",
    "trusted_referral",
)


